    from scipy.integrate import solve_ivp
    import numpy as np
    import matplotlib.pyplot as plt
    from psiop import PseudoDifferentialOperator

    print("="*70)
    print("COMPLETE EXAMPLE: PENDULUM WITH SYMPLECTIC STRUCTURE")
    print("="*70)

