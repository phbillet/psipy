        sol = solve_ivp(
            pendulum_system, t_span, [x0, xi0],
            t_eval=t_eval, method='DOP853', rtol=1e-10, atol=1e-12
        )
        solutions.append((sol, label))
        print(f"  {label:20s} : (x₀, ξ₀) = ({x0:.2f}, {xi0:.2f})")

